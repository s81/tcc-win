/*
 * Hand-written x86-64 stand-ins for code that tcc-win does NOT generate today
 * (docs/JIT-DESIGN.md, goal 1a). They bound what each design option could
 * reach on this machine when no reference compiler is installed. They are
 * proxies written by hand, not compiler output.
 *
 *   *_peep  locals stay in the stack frame; loop rotated (test at the bottom),
 *           no jump-to-jump, no reload of a value still in a register,
 *           load-op-store folded.  = single pass + peephole, no register allocation
 *   *_regmov  see the end of this file: tcc's code with slots turned into registers
 *   *_b     see the end of this file: the design target for option B
 *   *_reg   non-address-taken locals live in registers; nothing hoisted,
 *           nothing if-converted, nothing vectorized.  = single pass + register locals
 *   *_cmov / *_simd   need an IR: if-conversion, loop-invariant motion, vectorization
 *
 * Same signature and results as tests/jitbench/kernels.c:
 *   uint64_t k_NAME(const uint8_t *src (rcx), uint8_t *dst (rdx), size_t n (r8))
 * Opcodes tcc's assembler lacks are given as .byte with the mnemonic in a comment.
 * run: jitbench kern tests/jitbench/asmproxy.c bytesum_reg 64 7 b 1
 */
